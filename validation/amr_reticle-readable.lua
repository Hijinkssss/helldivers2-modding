            animation_resource_offset=found.animation_states[1].bytes:byte(0x10),
            animation_states_offset=found.animation_states[1].bytes:byte(0x44)}
    end
    return function()
        if attempted then return cached,failure end
        local exe, game = api.module('helldivers2.exe'),api.module('game.dll')
        if not exe or not game or exe < 65536 or game < 65536 then return nil,'AMR modules unavailable' end
