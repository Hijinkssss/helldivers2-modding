            optional >= 0xf0 and optional <= 1024 and size > 4096 and size <= 536870912 and
            base+size < 2^47 and pe_at+24+optional+count*40 <= size, 'invalid PE sections')
        local sections, table_bytes = {}, read(base+pe_at+24+optional,count*40)
        for i=0,count-1 do
            local rva, length, flags = u32(table_bytes,i*40+12),u32(table_bytes,i*40+8),u32(table_bytes,i*40+36)
            assert(rva >= 4096 and length > 0 and rva+length <= size, 'invalid section range')
            sections[#sections+1] = {first=base+rva,last=base+rva+length,
                code=math.floor(flags/0x20000000)%2 == 1, writable=math.floor(flags/0x80000000)%2 == 1}
        end
        return {base=base,size=size,stamp=u32(pe,8),sections=sections}
    end
    local function contains(mod, at, size, kind)
        for _, section in ipairs(mod.sections) do
            if at >= section.first and at+size <= section.last then
                return kind == 'code' and section.code or kind ~= 'code' and not section.code and
                    (kind ~= 'global' or section.writable)
            end
        end
        return false
    end
