        ffi.cdef[[
            void * __stdcall GetModuleHandleA(const char *);
            void * __stdcall GetCurrentProcess(void);
            int __stdcall ReadProcessMemory(void *, const void *, void *, size_t, size_t *);
        ]]
        local process, buffer, copied = ffi.C.GetCurrentProcess(), ffi.new('uint8_t[65536]'), ffi.new('size_t[1]')
        api = {
            module=function(name) return tonumber(ffi.cast('uintptr_t',ffi.C.GetModuleHandleA(name))) end,
            address=function(world)
                assert(type(world) == 'userdata', 'unsupported world')
                return tonumber(ffi.cast('uintptr_t',world))
            end,
            read=function(at,size)
                assert(type(at) == 'number' and at >= 65536 and at % 1 == 0 and at+size < 2^47 and
                    size > 0 and size <= 65536, 'invalid read range')
                copied[0] = 0
                if ffi.C.ReadProcessMemory(process,ffi.cast('const void *',at),buffer,size,copied) ~= 0 and
                    tonumber(copied[0]) == size then return ffi.string(buffer,size) end
            end
        }
    end
    local cached, failure, attempted
    local function read(at, size)
        local data = api.read(at,size)
        assert(type(data) == 'string' and #data == size, 'unavailable contract memory')
        return data
    end
    local function u32(data, at)
        local a,b,c,d = data:byte(at+1,at+4)
        return a+b*256+c*65536+d*16777216
    end
    local function module(base)
        local dos = read(base,64)
        assert(dos:sub(1,2) == 'MZ', 'invalid module header')
        local pe_at = u32(dos,0x3c)
        assert(pe_at >= 64 and pe_at < 1048576, 'invalid PE offset')
        local pe = read(base+pe_at,0x58)
        local count = pe:byte(7)+pe:byte(8)*256
        local optional = pe:byte(21)+pe:byte(22)*256
        local size = u32(pe,0x50)
        assert(pe:sub(1,4) == 'PE\0\0' and pe:byte(5) == 0x64 and pe:byte(6) == 0x86 and
