        assert(selected.atlas.c45 == selected.atlas_lookup.address and
            selected.atlas_lookup.c1eb == selected.atlas_lookup.address, 'atlas lookup mismatch')
        assert(selected.animation_get.c25 == selected.unit_lookup.address and
            selected.animation_get.c56 == selected.animation_states.address, 'animation consumer mismatch')
        assert(hud.owner_offset == hud.owner_check and hud.flag_offset-hud.owner_offset == 0x209a, 'HUD owner mismatch')
        assert(dot.c22 == ring.c21 and dot.c79 == ring.c75 and dot.widget_offset < ring.widget_offset, 'widget constructor mismatch')
        assert(selected.root.cf == dot.c22 and selected.dot_shader.address == dot.address+0x35 and
            selected.ring_shader.address == ring.address+0x34, 'widget consumer mismatch')
        assert(selected.dot_shader.r56 == selected.ring_shader.r53 and
            selected.dot_shader.r88 == selected.ring_shader.r85, 'shadow shader mismatch')
        assert(read(selected.dot_shader.r56,16) == '\205\204\076\062'..string.rep('\0',12) and
