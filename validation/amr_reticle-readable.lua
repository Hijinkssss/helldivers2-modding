                                        rows[#rows+1] = {address=start+at-1,bytes=bytes:sub(at,at+recipe.size-1)}
                                    end
                                end
                                pos = pos+1
                            end
                        end
                        tail = bytes:sub(math.max(1,#bytes-overlap+1))
                    end
                end
            end
            end
        end
        for _, recipe in ipairs(recipes) do
            if recipe.name ~= 'registration' then
